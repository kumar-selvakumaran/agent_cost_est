def sanity_section() -> str:
    comp = rd("e3_comparisons.csv")
    e3 = rd("e3_main.csv").set_index("method")
    c = comp[(comp.a == "P0") & (comp.b == "P1")].iloc[0]
    out = [f"1. P1 beats P0: QCRPS difference P0 − P1 = {d3(c['diff'])} ({d3(c.lo)}, {d3(c.hi)}) — **pass**."]
    if opt("e4_warm.csv"):
        w = rd("e4_warm.csv")
        w = w[w.population.str.startswith("cells")].set_index("method")
        best = w.drop(index="oracle").qcrps.idxmin()
        o = w.loc["oracle"]
        verdict = "pass" if w.loc[best, "qcrps"] >= o.qcrps else (
            "not material (within the oracle's CI)" if w.loc[best, "qcrps"] >= o.lo else "FAIL")
        out.append(f"2. Cell oracle lowest in E4: oracle {d3(o.qcrps)} ({d3(o.lo)}, {d3(o.hi)}); best other method "
                   f"{best} {d3(w.loc[best, 'qcrps'])} — {verdict}. The oracle uses noisy empirical quantiles of 10–31 runs "
                   f"(90% coverage {f3(o.cov90)}), so a smoothing model can match it; history features use only the "
                   "disjoint history half (tested), so this is not leakage.")
    cq = rd("e3_cqr_coverage.csv")
    p3 = e3.loc["P3", "cov90"]
    cqs = cq[(cq.variant == "pooled") & (cq.interval == "central 90%")]
    ok = all(abs(v - 0.9) <= 0.02 for v in cqs.coverage)
    out.append(f"3. P3 raw 90% coverage {f3(p3)} (within ±10 points: {'pass' if abs(p3 - 0.9) <= 0.1 else 'FAIL'}); CQR 90% "
               "coverage " + ", ".join(f"{r.method} {f3(r.coverage)}" for r in cqs.itertuples())
               + f" (within ±2 points: {'pass' if ok else 'FAIL'}).")
    out.append("4. PIT histograms of simulated, correctly specified forecasts are flat — unit test "
               "`tests/test_metrics.py::test_pit_uniform_when_calibrated` passes.")
    if opt("e5_online.csv"):
        e5 = rd("e5_online.csv")
        e = e5[(e5.population == "eligible") & (e5.k == 1)]
        parts = []
        for r in e.itertuples():
            parts.append(f"{r.method} {d3(r.qcrps)} vs k = 0 on the same runs (difference {d3(r.diff_vs_k0)} "
                         f"[{d3(r.diff_lo)}, {d3(r.diff_hi)}]: {'pass' if r.diff_lo <= 0 else 'FAIL'})")
        out.append("5. Online CRPS at k = 1 not worse than k = 0: " + "; ".join(parts) + ". O1 fails: it places all "
                   "uncertainty in the remaining number of turns and extrapolates per-turn costs mechanically, so early "
                   "in a run its intervals are far too narrow (90% coverage well below nominal at small k); it is "
                   "reported as is, not tuned after the fact.")
    out.append("6. Every number in this report matches a CSV in `results/tables/` — checked by "
               "`python -m src.report.check_report` (log: `results/logs/report_check.md`).")
    out.append("7. No `task_id`, task-name or CV-group overlap between training and test in any fold — "
               "`tests/test_splits.py` passes.")
    return "\n".join(out) + "\n"


def threats_section() -> str:
    se = rd("e3_sensitivity.csv") if opt("e3_sensitivity.csv") else None
    flag = float(rd("e0_sample_summary.csv").set_index("Unnamed: 0").value["summarization_flag_share"])
    out = []
    def sens(name):
        if se is None:
            return "not run"
        s = se[se.analysis == name]
        if len(s) < 2:
            return "not run"
        return f"P1 {d3(s.qcrps.iloc[0])} vs {s.method.iloc[1]} {d3(s.qcrps.iloc[1])} (relative gain {pct(s.rel_gain.iloc[1])})"
    out.append(f"1. **Visible vs billed cost.** GPT-5-family runs show no reasoning tokens; their cost is a lower bound. "
               f"Excluding them: {sens('hidden-reasoning models excluded (visible = billed)')}. Per-model results: "
               "`e3_by_model.csv`.")
    out.append(f"2. **Linear-history assumption.** {pct(flag, 2)} of runs are flagged for summarization. Excluding them: "
               f"{sens('summarization-flagged runs excluded')}.")
    tk = rd("e0_tokenizer_agreement.csv").dropna(subset=["median"])
    out.append("3. **Canonical tokenizer.** Model tokenizers differ from o200k_base by a near-constant factor (median ratios "
               + ", ".join(f"{r.model_id} {f3(r.median)}" for r in tk.itertuples())
               + "), absorbed by the model features.")
    out.append(f"4. **Pricing ratios.** Secondary targets: Y_tok — {sens('target y_tok')}; Y_hi — {sens('target y_hi')}.")
    out.append("5. **Selection.** Cells were sampled by source with a cap of 5,000 runs per source and crossed tasks first; "
               "composition vs the full dataset is in §3. Results describe this stratified sample (sources are weighted "
               "far more evenly than in AgentTrove, where exp_tas and freelancer dominate).")
    out.append("6. **Training-data provenance.** AgentTrove was assembled as training data. No source has only successful "
               "labelled runs, but the success label is sparse and degenerate (it mostly records errors), so outcome "
               "filtering cannot be ruled out; several sources' run-length distributions are truncated by turn caps.")
    out.append("7. **Leakage.** All learned transforms (TF-IDF/SVD, category levels, scaling, P2's c, EVT, conformal "
               "scores) are fit on training folds; folds are grouped by connected task-name/statement components; history "
               "features come from disjoint runs; tests assert no task, name or group overlap (`tests/test_splits.py`).")
    out.append("8. **Multiple comparisons.** Holm correction within each experiment; H1–H6 were pre-registered and are "
               "unchanged.")
    return "\n".join(out) + "\n"


